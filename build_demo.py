def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Build a complete single-document MatSci-RAG demo database from PDF "
            "or Markdown using the repository processing pipeline."
        )
    )
    parser.add_argument("--input", required=True, help="Input PDF or Doc2X-style Markdown")
    parser.add_argument(
        "--workspace",
        default=None,
        help="Workspace root; defaults to <input_stem>_matsci_rag_demo beside input",
    )
    parser.add_argument("--doc_id", default=None, help="Optional stable document ID")
    parser.add_argument(
        "--source_file",
        default=None,
        help="Optional provenance label, normally the original PDF filename",
    )
    parser.add_argument(
        "--no_copy_source",
        action="store_true",
        help="Do not copy the input file into workspace/source",
    )

    # Doc2X
    parser.add_argument("--doc2x_env", default=None, help="Env file for DOC2X_API_KEY/API_KEY")
    parser.add_argument("--doc2x_debug", action="store_true")
    parser.add_argument("--keep_doc2x_zip", action="store_true")
    parser.add_argument("--force_doc2x", action="store_true")
    parser.add_argument("--doc2x_output_format", default="md_dollar")

    # Metadata LLM
    parser.add_argument("--llm_env", default=None, help="Env file for metadata-structuring LLM")
    parser.add_argument("--metadata_model", default=DEFAULT_METADATA_MODEL)
    parser.add_argument("--metadata_debug", action="store_true")
    parser.add_argument("--force_metadata", action="store_true")
    parser.add_argument("--skip_metadata", action="store_true")

    # Chunking / embedding
    parser.add_argument("--spacy_model", default=DEFAULT_SPACY_MODEL)
    parser.add_argument(
        "--tokenizer_model",
        default=None,
        help="Tokenizer name/path; defaults to --embedding_model",
    )
    parser.add_argument("--embedding_model", default=DEFAULT_EMBEDDING_MODEL)
    parser.add_argument(
        "--rerank_model",
        default=DEFAULT_RERANK_MODEL,
        help="Recorded for downstream main_pipeline configuration; not loaded during build",
    )
    parser.add_argument("--device", default="auto")
    parser.add_argument("--max_chunk_tokens", type=int, default=DEFAULT_MAX_CHUNK_TOKENS)
    parser.add_argument("--chunk_overlap", type=int, default=DEFAULT_CHUNK_OVERLAP)
    parser.add_argument("--skip_embedding", action="store_true")
    parser.add_argument("--embedding_verbose", action="store_true")

    args = parser.parse_args()

    build_demo(
        input_file=args.input,
        workspace=args.workspace,
        doc_id=args.doc_id,
        source_file=args.source_file,
        copy_source=not args.no_copy_source,
        doc2x_env=args.doc2x_env,
        doc2x_debug=args.doc2x_debug,
        doc2x_keep_zip=args.keep_doc2x_zip,
        doc2x_force=args.force_doc2x,
        doc2x_output_format=args.doc2x_output_format,
        llm_env=args.llm_env,
        metadata_model=args.metadata_model,
        metadata_debug=args.metadata_debug,
        metadata_force=args.force_metadata,
        skip_metadata=args.skip_metadata,
        skip_embedding=args.skip_embedding,
        spacy_model=args.spacy_model,
        tokenizer_model=args.tokenizer_model,
        embedding_model=args.embedding_model,
        rerank_model=args.rerank_model,
        device=args.device,
        max_chunk_tokens=args.max_chunk_tokens,
        chunk_overlap=args.chunk_overlap,
        embedding_verbose=args.embedding_verbose,
    )


if __name__ == "__main__":
    main()
