# 1. Individual stages
# ============================================================

def run_pdf_stage(
    pdf_path: Path,
    doc2x_output_dir: Path,
    env_file: Optional[str],
    debug: bool,
    keep_zip: bool,
    force: bool,
    output_format: str,
) -> Path:
    from pdf_to_md import pdf_to_md

    return pdf_to_md(
        pdf_file=pdf_path,
        output_dir=doc2x_output_dir,
        env_file_path=env_file,
        debug=debug,
        remove_zip=not keep_zip,
        output_format=output_format,
        force=force,
    )


def run_clean_stage(markdown_path: Path, cleaned_path: Path) -> Path:
    from clean_md import clean_markdown_file

    return clean_markdown_file(
        input_path=markdown_path,
        output_path=cleaned_path,
        rebase_assets=True,
    )


def run_md_json_stage(
    cleaned_path: Path,
    json_path: Path,
    doc_id: str,
    source_file: str,
) -> Path:
    from md_json import convert_markdown_file

    return convert_markdown_file(
        input_path=cleaned_path,
        output_path=json_path,
        doc_id=doc_id,
        source_file=source_file,
    )


def run_graph_stage(
    json_path: Path,
    output_dir: Path,
    doc_id: str,
    spacy_model: str,
    tokenizer_model: str,
    max_chunk_tokens: int,
    chunk_overlap: int,
) -> Dict[str, Path]:
    from json_split import (
        build_evidence_graph_from_md_json,
        read_json,
        write_json as write_graph_json,
        write_jsonl,
    )

    data = read_json(str(json_path))
    source_file = str(data.get("source_file") or json_path.name)

    graph, retrieval_docs = build_evidence_graph_from_md_json(
        data=data,
        source_file=source_file,
        doc_id=doc_id,
        spacy_model=spacy_model,
        tokenizer_model=tokenizer_model,
        max_chunk_tokens=max_chunk_tokens,
        chunk_overlap=chunk_overlap,
    )

    output_dir.mkdir(parents=True, exist_ok=True)
    graph_path = output_dir / "paper_graph.json"
    retrieval_path = output_dir / "retrieval_docs.jsonl"
    write_graph_json(str(graph_path), graph)
    write_jsonl(str(retrieval_path), retrieval_docs)

    print("[OK] Evidence graph built")
    print(f"[GRAPH]     {graph_path}")
    print(f"[RETRIEVAL] {retrieval_path}")
    print("[STATS]")
    print(json.dumps(graph.get("stats", {}), ensure_ascii=False, indent=2))

    return {
        "graph": graph_path,
        "retrieval_docs": retrieval_path,
    }


def run_metadata_stage(
    json_path: Path,
    output_dir: Path,
    doc_id: str,
    env_file: Optional[str],
    model_name: str,
    tokenizer_model: str,
    max_embedding_tokens: int,
    debug: bool,
    force: bool,
) -> Dict[str, Any]:
    from metadata_processor import process_metadata

    return process_metadata(
        input_json_path=str(json_path),
        output_dir=str(output_dir),
        env_file_path=env_file,
        model_name=model_name,
        tokenizer_model=tokenizer_model,
        max_embedding_tokens=max_embedding_tokens,
        doc_id=doc_id,
        debug=debug,
        force=force,
    )


def run_merge_stage(
    graph_path: Path,
    metadata_node_path: Path,
    report_path: Path,
) -> Dict[str, Any]:
    from merge_metadata_to_graph import (
        merge_metadata_node_into_graph,
        read_json,
        write_json as write_merge_json,
    )

    graph_data = read_json(graph_path)
    metadata_node = read_json(metadata_node_path)

    merged_graph, report = merge_metadata_node_into_graph(
        graph_data=graph_data,
        metadata_node=metadata_node,
        replace_existing=True,
        update_enrichment_status=True,
        allow_source_file_mismatch=False,
    )

    write_merge_json(graph_path, merged_graph)
    write_merge_json(report_path, report)

    print("[OK] metadata_structured merged into paper_graph.json")
    print(f"[REPORT] {report_path}")
    return report


def run_embedding_stage(
    output_dir: Path,
    embedding_model: str,
    device: str,
    verbose: bool,
) -> Dict[str, Any]:
    from embedding_json import build_indexes

    return build_indexes(
        output_dir=str(output_dir),
        model_name=embedding_model,
        device=device,
        retrieval_jsonl=None,
        graph_json=None,
        index_dir=None,
        trust_remote_code=True,
        normalize_embeddings=True,
        verbose=verbose,
    )


