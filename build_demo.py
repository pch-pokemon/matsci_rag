def _now() -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S")


def write_json(path: str | Path, data: Any) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def _strip_processing_suffixes(stem: str) -> str:
    for suffix in (".cleaned", "_cleaned", "-cleaned"):
        if stem.lower().endswith(suffix):
            return stem[: -len(suffix)]
    return stem


def infer_doc_id(input_path: str | Path) -> str:
    return _strip_processing_suffixes(Path(input_path).stem) or "document"


def default_workspace(input_path: str | Path) -> Path:
    p = Path(input_path)
    return p.parent / f"{infer_doc_id(p)}_matsci_rag_demo"


