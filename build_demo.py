def copy_source_file(input_path: Path, source_dir: Path) -> Path:
    """
    Copy the source file into workspace/source.

    For Markdown input, also copy a sibling `images/` directory when present,
    so the demo workspace remains self-contained and local figure references
    can still be resolved after the Markdown file is moved.
    """
    source_dir.mkdir(parents=True, exist_ok=True)

    target = source_dir / input_path.name

    if input_path.resolve() != target.resolve():
        shutil.copy2(input_path, target)

    # Markdown input may rely on a sibling images/ directory generated by Doc2X.
    if input_path.suffix.lower() == ".md":
        source_images = input_path.parent / "images"
        target_images = source_dir / "images"

        if source_images.exists() and source_images.is_dir():
            if target_images.exists():
                shutil.rmtree(target_images)

            shutil.copytree(source_images, target_images)

            print(f"[ASSETS] Copied images directory:")
            print(f"         {source_images}")
            print(f"      -> {target_images}")
        else:
            print(
                f"[WARN] Markdown input has no sibling images directory: "
                f"{source_images}"
            )

    return target

def stage_header(number: int, title: str) -> None:
    print("\n" + "=" * 88)
    print(f"STEP {number}: {title}")
    print("=" * 88)


