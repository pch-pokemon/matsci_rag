def build_demo(
    input_file: str | Path,
    workspace: Optional[str | Path] = None,
    doc_id: Optional[str] = None,
    source_file: Optional[str] = None,
    copy_source: bool = True,
    doc2x_env: Optional[str] = None,
    doc2x_debug: bool = False,
    doc2x_keep_zip: bool = False,
    doc2x_force: bool = False,
    doc2x_output_format: str = "md_dollar",
    llm_env: Optional[str] = None,
    metadata_model: str = DEFAULT_METADATA_MODEL,
    metadata_debug: bool = False,
    metadata_force: bool = False,
    skip_metadata: bool = False,
    skip_embedding: bool = False,
    spacy_model: str = DEFAULT_SPACY_MODEL,
    tokenizer_model: Optional[str] = None,
    embedding_model: str = DEFAULT_EMBEDDING_MODEL,
    rerank_model: str = DEFAULT_RERANK_MODEL,
    device: str = "auto",
    max_chunk_tokens: int = DEFAULT_MAX_CHUNK_TOKENS,
    chunk_overlap: int = DEFAULT_CHUNK_OVERLAP,
    embedding_verbose: bool = False,
) -> Dict[str, Any]:
    input_path = Path(input_file).resolve()
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")
    if input_path.suffix.lower() not in {".pdf", ".md"}:
        raise ValueError("--input must be a .pdf or .md file")

    resolved_doc_id = (doc_id or "").strip() or infer_doc_id(input_path)
    workspace_path = Path(workspace).resolve() if workspace else default_workspace(input_path).resolve()
    source_dir = workspace_path / "source"
    doc2x_output_dir = workspace_path / "doc2x_output"
    intermediate_dir = workspace_path / "intermediate"
    output_dir = workspace_path / "output"

    for d in (workspace_path, source_dir, intermediate_dir, output_dir):
        d.mkdir(parents=True, exist_ok=True)

    tokenizer_model = tokenizer_model or embedding_model

    # The reranker is not needed to build FAISS indexes, but is captured in the
    # build summary because the same workspace is intended for main_pipeline.py.
    summary: Dict[str, Any] = {
        "schema_version": "1.0-demo-build",
        "started_at": _now(),
        "input": str(input_path),
        "workspace": str(workspace_path),
        "doc_id": resolved_doc_id,
        "configuration": {
            "spacy_model": spacy_model,
            "tokenizer_model": tokenizer_model,
            "embedding_model": embedding_model,
            "rerank_model": rerank_model,
            "device": device,
            "max_chunk_tokens": max_chunk_tokens,
            "chunk_overlap_sentences": chunk_overlap,
            "metadata_model": metadata_model,
            "metadata_enabled": not skip_metadata,
            "embedding_enabled": not skip_embedding,
            "doc2x_output_format": doc2x_output_format,
        },
        "steps": {},
        "outputs": {},
    }

    # --------------------------------------------------------
    # Source + PDF/Markdown input
    # --------------------------------------------------------
    if copy_source:
        working_source = copy_source_file(input_path, source_dir)
    else:
        working_source = input_path

    summary["outputs"]["source"] = str(working_source)

    if input_path.suffix.lower() == ".pdf":
        stage_header(1, "PDF -> Markdown (Doc2X)")
        markdown_path = run_pdf_stage(
            pdf_path=working_source,
            doc2x_output_dir=doc2x_output_dir,
            env_file=doc2x_env,
            debug=doc2x_debug,
            keep_zip=doc2x_keep_zip,
            force=doc2x_force,
            output_format=doc2x_output_format,
        )
        source_label = Path(source_file).name if source_file else input_path.name
        summary["steps"]["pdf_to_md"] = "completed"
    else:
        stage_header(1, "Markdown input (Doc2X stage skipped)")
        markdown_path = working_source
        source_label = Path(source_file).name if source_file else input_path.name
        summary["steps"]["pdf_to_md"] = "skipped_markdown_input"
        print(f"[MD] {markdown_path}")

    summary["outputs"]["markdown"] = str(markdown_path)
    summary["source_file"] = source_label

    # --------------------------------------------------------
    # Clean Markdown
    # --------------------------------------------------------
    stage_header(2, "Markdown normalization")
    cleaned_path = intermediate_dir / f"{resolved_doc_id}.cleaned.md"
    run_clean_stage(markdown_path, cleaned_path)
    summary["steps"]["clean_md"] = "completed"
    summary["outputs"]["cleaned_markdown"] = str(cleaned_path)
    print(f"[OK] {cleaned_path}")

    # --------------------------------------------------------
    # Markdown -> structured JSON
    # --------------------------------------------------------
    stage_header(3, "Markdown -> structured JSON")
    json_path = intermediate_dir / f"{resolved_doc_id}.json"
    run_md_json_stage(
        cleaned_path=cleaned_path,
        json_path=json_path,
        doc_id=resolved_doc_id,
        source_file=source_label,
    )
    summary["steps"]["md_json"] = "completed"
    summary["outputs"]["structured_json"] = str(json_path)
    print(f"[OK] {json_path}")

    # --------------------------------------------------------
    # JSON -> graph + retrieval docs
    # --------------------------------------------------------
    stage_header(4, "Structured JSON -> evidence graph")
    graph_outputs = run_graph_stage(
        json_path=json_path,
        output_dir=output_dir,
        doc_id=resolved_doc_id,
        spacy_model=spacy_model,
        tokenizer_model=tokenizer_model,
        max_chunk_tokens=max_chunk_tokens,
        chunk_overlap=chunk_overlap,
    )
    summary["steps"]["json_split"] = "completed"
    summary["outputs"].update({k: str(v) for k, v in graph_outputs.items()})

    # --------------------------------------------------------
    # Metadata enrichment + merge
    # --------------------------------------------------------
    if skip_metadata:
        stage_header(5, "Metadata enrichment skipped")
        summary["steps"]["metadata_processor"] = "skipped"
        summary["steps"]["merge_metadata"] = "skipped"
    else:
        stage_header(5, "Structured metadata enrichment")
        metadata_summary = run_metadata_stage(
            json_path=json_path,
            output_dir=output_dir,
            doc_id=resolved_doc_id,
            env_file=llm_env,
            model_name=metadata_model,
            tokenizer_model=tokenizer_model,
            max_embedding_tokens=max_chunk_tokens,
            debug=metadata_debug,
            force=metadata_force,
        )
        summary["steps"]["metadata_processor"] = "completed"
        summary["metadata"] = metadata_summary

        metadata_node_path = output_dir / "metadata_node.json"
        merge_report_path = output_dir / "metadata_merge_report.json"

        stage_header(6, "Merge metadata into evidence graph")
        merge_report = run_merge_stage(
            graph_path=graph_outputs["graph"],
            metadata_node_path=metadata_node_path,
            report_path=merge_report_path,
        )
        summary["steps"]["merge_metadata"] = "completed"
        summary["metadata_merge"] = merge_report
        summary["outputs"]["metadata_node"] = str(metadata_node_path)
        summary["outputs"]["metadata_merge_report"] = str(merge_report_path)

    # --------------------------------------------------------
    # Embedding / FAISS
    # --------------------------------------------------------
    if skip_embedding:
        stage_header(7, "Embedding / FAISS indexing skipped")
        summary["steps"]["embedding_json"] = "skipped"
    else:
        stage_header(7, "Embedding + FAISS indexing")
        manifest = run_embedding_stage(
            output_dir=output_dir,
            embedding_model=embedding_model,
            device=device,
            verbose=embedding_verbose,
        )
        summary["steps"]["embedding_json"] = "completed"
        summary["faiss_manifest"] = manifest
        summary["outputs"]["faiss_index_dir"] = str(output_dir / "faiss_section_indexes")

    summary["completed_at"] = _now()
    summary_path = workspace_path / "build_demo_summary.json"
    summary["outputs"]["build_summary"] = str(summary_path)
    write_json(summary_path, summary)

    print("\n" + "=" * 88)
    print("DEMO DATABASE BUILD COMPLETED")
    print("=" * 88)
    print(f"[WORKSPACE] {workspace_path}")
    print(f"[GRAPH]     {output_dir / 'paper_graph.json'}")
    print(f"[RETRIEVAL] {output_dir / 'retrieval_docs.jsonl'}")
    if not skip_embedding:
        print(f"[FAISS]     {output_dir / 'faiss_section_indexes'}")
    print(f"[SUMMARY]   {summary_path}")

    return summary


